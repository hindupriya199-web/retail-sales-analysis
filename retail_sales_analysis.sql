USE retail_sales_db;
-- 1. Find the total number of customers in each city.
SELECT
    city,
    COUNT(customer_ID) AS total_customers
FROM customers
GROUP BY city;

-- 2. Find the total sales amount for each product.
SELECT
    p.product_ID,
    p.product_name,
    COALESCE(SUM(o.total_amount), 0) AS total_sales
FROM products p
LEFT JOIN orders o
    ON p.product_ID = o.product_ID
GROUP BY p.product_ID, p.product_name;

-- 3. Find the total quantity sold for each product.
SELECT
    p.product_ID,
    p.product_name,
    COALESCE(SUM(o.quantity), 0) AS total_quantity
FROM products p
LEFT JOIN orders o
    ON p.product_ID = o.product_ID
GROUP BY p.product_ID, p.product_name;

-- 4. Find the total sales amount for each customer.
SELECT
    c.customer_ID,
    c.customer_name,
    COALESCE(SUM(o.total_amount), 0) AS total_sales
FROM customers c
LEFT JOIN orders o
    ON c.customer_ID = o.customer_ID
GROUP BY c.customer_ID, c.customer_name;

-- 5. Find the total sales amount for each product category.
SELECT
    p.category,
    COALESCE(SUM(o.total_amount), 0) AS total_sales
FROM products p
LEFT JOIN orders o
    ON p.product_ID = o.product_ID
GROUP BY p.category;

-- 6. Find the total sales amount for each city.
SELECT
    c.city,
    COALESCE(SUM(o.total_amount), 0) AS total_sales
FROM customers c
LEFT JOIN orders o
    ON c.customer_ID = o.customer_ID
GROUP BY c.city;

-- 7. Find the cities where total sales are greater than 5000.
SELECT
    c.city,
    SUM(o.total_amount) AS total_sales
FROM customers c
LEFT JOIN orders o
    ON c.customer_ID = o.customer_ID
GROUP BY c.city
HAVING SUM(o.total_amount) > 5000;

-- 8. Find products whose total quantity sold is greater than 2.
SELECT
    p.product_ID,
    p.product_name,
    SUM(o.quantity) AS total_quantity
FROM products p
INNER JOIN orders o
    ON p.product_ID = o.product_ID
GROUP BY p.product_ID, p.product_name
HAVING SUM(o.quantity) > 2;

-- 9. Find customers who have placed more than one order.
SELECT
    c.customer_ID,
    c.customer_name,
    COUNT(o.order_ID) AS total_orders
FROM customers c
LEFT JOIN orders o
    ON c.customer_ID = o.customer_ID
GROUP BY c.customer_ID, c.customer_name
HAVING COUNT(o.order_ID) > 1;

-- 10. Find the top 3 products with the highest total sales.
SELECT
    p.product_ID,
    p.product_name,
    COALESCE(SUM(o.total_amount), 0) AS total_sales
FROM products p
LEFT JOIN orders o
    ON p.product_ID = o.product_ID
GROUP BY p.product_ID, p.product_name
ORDER BY total_sales DESC
LIMIT 3;

-- 11. Find the customer who has spent the highest total amount.
SELECT
    c.customer_ID,
    c.customer_name,
    SUM(o.total_amount) AS highest_total_amount
FROM customers c
INNER JOIN orders o
    ON c.customer_ID = o.customer_ID
GROUP BY c.customer_ID, c.customer_name
ORDER BY highest_total_amount DESC
LIMIT 1;

-- 12. Find products that have never been ordered.
SELECT
    p.product_ID,
    p.product_name
FROM products p
LEFT JOIN orders o
    ON p.product_ID = o.product_ID
WHERE o.product_ID IS NULL;

-- 13. Find the total revenue generated by each product category
-- and display only categories with revenue greater than 5000.
SELECT
    p.category,
    SUM(o.total_amount) AS total_revenue
FROM products p
INNER JOIN orders o
    ON p.product_ID = o.product_ID
GROUP BY p.category
HAVING SUM(o.total_amount) > 5000;

-- 14. Find the average order value for each customer.
SELECT
    c.customer_ID,
    c.customer_name,
    AVG(o.total_amount) AS average_order_value
FROM customers c
LEFT JOIN orders o
    ON c.customer_ID = o.customer_ID
GROUP BY c.customer_ID, c.customer_name;

-- 15. Find each customer's most recent order date.
SELECT
    c.customer_ID,
    c.customer_name,
    MAX(o.order_date) AS recent_order
FROM customers c
LEFT JOIN orders o
    ON c.customer_ID = o.customer_ID
GROUP BY c.customer_ID, c.customer_name
ORDER BY recent_order DESC;
